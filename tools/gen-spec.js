#!/usr/bin/env node
// Builds spec/calls.json from Microsoft's published PlayFab API descriptions.
//
//   git clone --depth 1 https://github.com/PlayFab/API_Specs.git /tmp/api-specs
//   node tools/gen-spec.js /tmp/api-specs
//
// The descriptions are Apache-2.0 (see spec/LICENSE-APACHE and spec/NOTICE).
// We keep only what the server and the tests need: each call's address, how it
// signs in, and the shape of what goes in and comes out. Descriptions are left out.
'use strict';

const fs = require('node:fs');
const path = require('node:path');
const { execFileSync } = require('node:child_process');

const repo = process.argv[2];
if (!repo) {
  console.error('Usage: node tools/gen-spec.js <path to a clone of PlayFab/API_Specs>');
  process.exit(1);
}
const dir = path.join(repo, 'Legacy', 'PlayFab');
const files = fs.readdirSync(dir).filter((f) => f.endsWith('.api.json')).sort();

// Leaderboards.api.json and Progression.api.json both describe /Leaderboard and
// /Statistic. Progression is the newer one, so it wins.
const preferred = ['Progression.api.json'];
files.sort((a, b) => (preferred.includes(a) ? 1 : 0) - (preferred.includes(b) ? 1 : 0));

let commit = 'unknown';
let date = 'unknown';
try {
  [commit, date] = execFileSync('git', ['-C', repo, 'log', '-1', '--format=%H %cs'], { encoding: 'utf8' }).trim().split(' ');
} catch (e) { /* not a git clone */ }

const out = {
  about: 'Generated by tools/gen-spec.js. Do not edit by hand.',
  source: { repo: 'https://github.com/PlayFab/API_Specs', commit, date, license: 'Apache-2.0' },
  errors: {},
  calls: {},
  types: {},
};

for (const file of files) {
  const spec = JSON.parse(fs.readFileSync(path.join(dir, file), 'utf8'));
  const api = spec.name;

  for (const [name, err] of Object.entries(spec.errors || {})) out.errors[name] = err.id;

  const types = (out.types[api] = out.types[api] || {});
  for (const [name, t] of Object.entries(spec.datatypes || {})) {
    if (t.isenum) {
      types[name] = { e: (t.enumvalues || []).map((v) => v.name) };
      continue;
    }
    types[name] = {
      p: (t.properties || []).map((p) => [
        p.name,
        p.jsontype,
        p.actualtype,
        p.optional ? 1 : 0,
        p.collection || null,
        p.isclass ? 1 : 0,
        p.isenum ? 1 : 0,
      ]),
    };
  }

  for (const c of spec.calls || []) {
    const dep = c.deprecation || null;
    out.calls[c.url] = {
      api,
      name: c.name,
      group: c.subgroup || null,
      auth: c.auth,
      request: c.request,
      result: c.result,
      entityTypes: c.allowedentitytokentypes || null,
      retired: dep ? { after: dep.ObsoleteAfter || dep.DeprecatedAfter || null, replacedBy: dep.ReplacedBy || null } : null,
    };
  }
}

const target = path.join(__dirname, '..', 'spec', 'calls.json');
fs.writeFileSync(target, JSON.stringify(out) + '\n');
const n = Object.keys(out.calls).length;
const retired = Object.values(out.calls).filter((c) => c.retired).length;
console.log(`Wrote ${path.relative(process.cwd(), target)}: ${n} calls (${retired} marked as retired by Microsoft), commit ${commit.slice(0, 7)} of ${date}.`);
